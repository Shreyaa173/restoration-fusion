class Expert:
    def __init__(self, model, layer_fn, use_input):
        self.model = model.eval().to(dev)
        for p in self.model.parameters(): p.requires_grad_(False)
        self.feat = None
        def hook(mod, inp, out): self.feat = inp[0] if use_input else out
        layer_fn(self.model).register_forward_hook(hook)
    @torch.no_grad()
    def __call__(self, x):
        y = self.model(x)
        if isinstance(y, (list, tuple)): y = y[-1]
        return y, self.feat

