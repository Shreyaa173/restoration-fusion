from typing import Optional
from fastapi import FastAPI, File, Form, UploadFile, HTTPException
from fastapi.middleware.cors import CORSMiddleware

app = FastAPI(title="DFFN deblurring API")
app.add_middleware(CORSMiddleware, allow_origins=["*"], allow_methods=["*"], allow_headers=["*"])
gpu_lock = threading.Lock()

@app.get("/health")
def health():
    return {"status": "ok", "gpu": torch.cuda.get_device_name(0), "max_side": MAX_SIDE, "tta": USE_TTA,
            "models": {"deblur": {k: EXPERTS[k] is not None for k in ORDER}},
            "fusion_trained": {"deblur": bool(FUSION_TRAINED)}, "fusion_arch": FUSION_ARCH}

@app.post("/restore")
def restore(image: UploadFile = File(...), task: str = Form("deblur"), gt: Optional[UploadFile] = File(None)):
    if task != "deblur": raise HTTPException(400, "This backend only supports task 'deblur'")
    try:
        img_bytes = image.file.read(); gt_bytes = gt.file.read() if gt is not None else None
        with gpu_lock:
            return run_pipeline(img_bytes, gt_bytes)
    except HTTPException: raise
    except Exception as e:
        raise HTTPException(500, f"{type(e).__name__}: {e}")

