# %% [markdown]
# ## 6. Pipeline and metrics
# Scores use the DFFN notebook's own `score` (outputs rounded to 8 bit, PSNR from MSE, SSIM from `pytorch_msssim`), RGB for deblurring.

# %%
from PIL import Image
from pytorch_msssim import ssim as ssim_fn

def load_rgb(data: bytes, max_side=MAX_SIDE, size=None):
    im = Image.open(io.BytesIO(data)).convert("RGB")
    if size is not None:
        if im.size != size: im = im.resize(size, Image.LANCZOS)
    else:
        s = max(im.size)
        if s > max_side:
            r = max_side / s; im = im.resize((max(32, round(im.width * r)), max(32, round(im.height * r))), Image.LANCZOS)
    return im

def run_experts(x):
    """x: [1,3,h,w] in 0..1. Returns per-expert outputs/features (cropped back to h x w), timings and notes."""
    h, w = x.shape[-2:]
    H, Wd = math.ceil(h / 32) * 32, math.ceil(w / 32) * 32
    mode = "reflect" if (H - h < h and Wd - w < w) else "replicate"
    xp = F.pad(x, (0, Wd - w, 0, H - h), mode=mode) if (H, Wd) != (h, w) else x
    outs, feats, ms, notes = {}, {}, {}, {}
    for key in ORDER:
        e = EXPERTS[key]
        if e is None: notes[key] = "Not loaded: " + LOAD_NOTES.get(key, "unknown"); continue
        try:
            torch.cuda.synchronize(); t = time.time()
            y, f = e(xp); torch.cuda.synchronize()
            outs[key], feats[key], ms[key] = y[..., :h, :w].clamp(0, 1), f[..., :h, :w], round((time.time() - t) * 1000)
        except torch.cuda.OutOfMemoryError:
            torch.cuda.empty_cache(); notes[key] = "Out of GPU memory. Try a smaller image."
        except Exception as ex:
            notes[key] = f"{type(ex).__name__}: {str(ex)[:160]}"
    return outs, feats, ms, notes

def to_u8(t):  # [1,3,H,W] -> HxWx3 uint8
    return (t.clamp(0, 1)[0].permute(1, 2, 0).cpu().numpy() * 255.0).round().astype(np.uint8)

def data_url(u8):
    buf = io.BytesIO(); Image.fromarray(u8).save(buf, "PNG")
    return "data:image/png;base64," + base64.b64encode(buf.getvalue()).decode()

def score(pred, gt):  # both [1,3,H,W] in 0..1, RGB
    p, g = (pred.clamp(0, 1) * 255).round() / 255, (gt * 255).round() / 255
    mse = F.mse_loss(p, g).item()
    try: s = ssim_fn(p, g, data_range=1.0, size_average=True).item()
    except Exception: s = None          # images smaller than the SSIM window
    return 10 * math.log10(1.0 / max(mse, 1e-10)), s

TRUST_COLORS = {"hinet": (59, 130, 246), "sfnet": (245, 158, 11), "nafnet": (217, 70, 239)}   # same as the website legend

def make_trust(wmap, base):
    """Colour every pixel by the experts DFFN trusts there, over a greyscale copy of the output."""
    cols = torch.tensor([TRUST_COLORS[k] for k in ORDER], device=wmap.device, dtype=torch.float32).view(1, 3, 3, 1, 1) / 255.0
    col = (wmap[:, :, None] * cols).sum(1)
    gray = base.mean(1, keepdim=True).expand(-1, 3, -1, -1)
    ov = 0.35 * gray + 0.65 * col
    share = wmap.mean(dim=(0, 2, 3)).tolist()
    return {"image": data_url(to_u8(ov)), "share": {k: round(100 * v, 1) for k, v in zip(ORDER, share)}}

def blank(key): return {"id": key, "name": DISPLAY[key], "available": False, "note": "", "image": None, "psnr": None, "ssim": None, "time_ms": None}

@torch.inference_mode()
def run_pipeline(image_bytes, gt_bytes=None):
    t_all = time.time()
    im = load_rgb(image_bytes)
    w, h = im.size
    x = torch.from_numpy(np.asarray(im, dtype=np.float32) / 255.0).permute(2, 0, 1)[None].to(dev)
    gt = None
    if gt_bytes: gt = torch.from_numpy(np.asarray(load_rgb(gt_bytes, size=im.size), dtype=np.float32) / 255.0).permute(2, 0, 1)[None].to(dev)

    outs, feats, ms, notes = run_experts(x)
    items, imgs, trust = [], {}, None
    for key in ORDER:
        it = blank(key)
        if key in outs: it.update(available=True, time_ms=ms[key]); imgs[key] = outs[key]
        else: it["note"] = notes.get(key, "No output")
        items.append(it)

    avg = blank("average")
    if outs:
        used = [k for k in ORDER if k in outs]
        imgs["average"] = torch.stack([outs[k] for k in used]).mean(0)
        avg.update(available=True, time_ms=0)
        if len(used) < 3: avg["note"] = "Mean of " + ", ".join(DISPLAY[k] for k in used) + " (the others are unavailable)."
    else: avg["note"] = "No expert produced an output."
    items.append(avg)

    fus = blank("fusion")
    if FUSION is not None and len(outs) == 3:
        try:
            torch.cuda.synchronize(); t = time.time()
            pred, wmap = FUSION([feats[k] for k in ORDER], [outs[k] for k in ORDER], x)
            if USE_TTA:                                   # flip ensemble, exactly as in the DFFN notebook's evaluation
                xf = x.flip(-1); o2, f2, _, _ = run_experts(xf)
                if len(o2) == 3: pred = (pred + FUSION([f2[k] for k in ORDER], [o2[k] for k in ORDER], xf)[0].flip(-1)) / 2
            torch.cuda.synchronize()
            pred = pred.clamp(0, 1); imgs["fusion"] = pred
            trust = make_trust(wmap, pred)
            fus.update(available=True, time_ms=round((time.time() - t) * 1000))
            if not FUSION_TRAINED: fus["note"] = "Placeholder: no trained DFFN checkpoint found, so this equals plain output averaging."
        except torch.cuda.OutOfMemoryError:
            torch.cuda.empty_cache(); fus["note"] = "Out of GPU memory. Try a smaller image."
        except Exception as ex:
            fus["note"] = f"{type(ex).__name__}: {str(ex)[:160]}"
    else:
        fus["note"] = "DFFN needs all three experts loaded. " + "; ".join(f"{DISPLAY[k]}: {v}" for k, v in notes.items())
    items.append(fus)

    for it in items:
        if it["id"] in imgs:
            it["image"] = data_url(to_u8(imgs[it["id"]]))
            if gt is not None: it["psnr"], it["ssim"] = score(imgs[it["id"]], gt)
    out = {"task": "deblur", "width": w, "height": h, "y_channel": False, "has_gt": gt is not None,
           "fusion_trained": bool(FUSION_TRAINED and FUSION is not None), "trust": trust, "tta": USE_TTA,
           "elapsed_ms": round((time.time() - t_all) * 1000), "input": data_url(np.asarray(im)), "results": items}
    del outs, feats, imgs; torch.cuda.empty_cache()
    return out

