def build_fusion(path):
    if not path:
        return DFFN().to(dev).eval(), False, "none (placeholder = plain average)"
    ck = tload(path)
    sd = strip_module(ck.get("model", ck.get("params", ck.get("state_dict", ck))))
    if "g_in.weight" not in sd:
        raise RuntimeError(f"{os.path.basename(path)} is not a gated DFFN checkpoint (no g_in.weight). Old 0.24M checkpoints are not supported here.")
    in_chs = tuple(sd[f"align.{i}.weight"].shape[1] for i in range(3))
    live = tuple(EXPERT_CHANNELS)
    if in_chs != live:
        raise RuntimeError(f"Feature widths differ: checkpoint expects {in_chs} (HINet, SFNet, NAFNet) but the experts here give {live}. "
                           "If the third differs, set NAFNET_TAP to the layer your v5 notebook used; if the checkpoint was trained with AdaIR "
                           "(third width 96) it cannot be used with NAFNet.")
    c = sd["align.0.weight"].shape[0]
    n_blocks = len({k.split(".")[1] for k in sd if k.startswith("refine.")})
    net = DFFN(in_chs, c, n_blocks)
    net.load_state_dict(sd, strict=True)
    return net.to(dev).eval(), True, f"DFFN (image-aware gate, c={c}, {n_blocks} blocks)"

