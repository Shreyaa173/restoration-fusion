def tload(path): return torch.load(path, map_location="cpu", weights_only=False)
def strip_module(sd): return {(k[7:] if k.startswith("module.") else k): v for k, v in sd.items()}
def find(*patterns):
    for pattern in patterns:
        hits = sorted(glob.glob(f"{W}/**/{pattern}", recursive=True))
