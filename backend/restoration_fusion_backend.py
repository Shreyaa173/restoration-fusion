# ## 3. Model wrappers
# Every wrapper returns `(restored_image, feature_map)`.
# The feature map is the input of the network's last 3-channel output convolution, i.e. the
# decoder feature right before it is turned into pixels. If a network has several such layers, the one
# that executes last wins (that is the full-resolution output head).

# %%
import numpy as np, yaml
import torch.nn as nn, torch.nn.functional as F

dev = "cuda"
CLASH = {"utils", "data", "models", "net", "options", "train", "eval", "main", "layers", "losses"}

def isolated_import(repo_dir, fn):
    """Import from one repo without leaving its generic top-level names (utils, models, ...)
    in sys.modules, because HINet / SFNet / AdaIR all use such names."""
    before = set(sys.modules)
    sys.path.insert(0, repo_dir)
    try:
        return fn()
    finally:
        sys.path.remove(repo_dir)
        for m in list(sys.modules):
            if m not in before and m.split(".")[0] in CLASH:
                del sys.modules[m]

def strip_module(sd):
    return {(k[7:] if k.startswith("module.") else k): v for k, v in sd.items()}

class FeatureTap:
    """Records the input of the most recently executed Conv2d(out_channels=3)."""
    def __init__(self, net, layer_name=None):
        self.feat, self.layer = None, None
        mods = dict(net.named_modules())
        targets = {layer_name: mods[layer_name]} if layer_name else \
                  {n: m for n, m in mods.items() if isinstance(m, nn.Conv2d) and m.out_channels == 3}
        assert targets, "no 3-channel output conv found; pass layer_name"
        for n, m in targets.items():
            m.register_forward_pre_hook(lambda mod, inp, n=n: self._store(n, inp[0]))
        self.candidates = list(targets)
    def _store(self, name, x):
        self.feat, self.layer = x.detach(), name

class Restorer:
    def __init__(self, key, name, net, tap_layer=None):
        self.key, self.name = key, name
        self.net = net.to(dev).eval()
        for p in self.net.parameters(): p.requires_grad_(False)
        self.tap = FeatureTap(self.net, tap_layer)
        self.feat_channels = None
    @torch.inference_mode()
    def __call__(self, x):
        self.tap.feat = None
        out = self.net(x)
        if isinstance(out, (list, tuple)): out = out[-1]
        feat = self.tap.feat
        self.feat_channels = feat.shape[1]
        return out.clamp(0, 1), feat

