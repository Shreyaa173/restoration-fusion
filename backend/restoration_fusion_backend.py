public_url = None
for line in tun.stdout:
    m = re.search(r"https://[a-z0-9-]+\.trycloudflare\.com", line)
    if m: public_url = m.group(0); break
print("\nBACKEND URL  ->", public_url)
threading.Thread(target=lambda: [None for _ in tun.stdout], daemon=True).start()   # keep draining the tunnel log

