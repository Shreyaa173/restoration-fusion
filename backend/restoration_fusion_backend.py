# %% [markdown]
# ## 4. Fusion module (our model, CMFNet-style, pixel-wise trust)
# * **Align**: 1x1 conv per model maps its features to a common width; they are resized to image size.
# * **Attention fusion**: channel attention picks useful features, then a head predicts one weight
#   per model per pixel (softmax over models).
# * **Image mix**: restored images are blended with those weights.
# * **Refine**: a small residual correction is added.
#
# Weight head and correction conv start at zero, so an untrained module equals a simple average.
# This is a working skeleton, since the final design is not decided yet. Edit freely, but keep the
# `forward(imgs, feats, mask)` signature so the server does not change.

# %%
class ChannelAttention(nn.Module):
    def __init__(self, c, r=4):
        super().__init__()
        self.f = nn.Sequential(nn.AdaptiveAvgPool2d(1), nn.Conv2d(c, max(c // r, 4), 1), nn.PReLU(), nn.Conv2d(max(c // r, 4), c, 1), nn.Sigmoid())
    def forward(self, x): return x * self.f(x)

class FusionModule(nn.Module):
    def __init__(self, feat_channels=(64, 32, 48), dim=32):
        super().__init__()
        self.k = len(feat_channels)
        self.align = nn.ModuleList([nn.Conv2d(c, dim, 1) for c in feat_channels])
        self.fuse = nn.Sequential(nn.Conv2d(dim * self.k, dim, 3, padding=1), nn.PReLU(), ChannelAttention(dim))
        self.weight_head = nn.Conv2d(dim, self.k, 3, padding=1)
        self.refine = nn.Sequential(nn.Conv2d(dim, dim, 3, padding=1), nn.PReLU(), nn.Conv2d(dim, 3, 3, padding=1))
        for m in (self.weight_head, self.refine[-1]):
            nn.init.zeros_(m.weight); nn.init.zeros_(m.bias)

    def forward(self, imgs, feats, mask):
        """imgs: K tensors [B,3,H,W]; feats: K tensors [B,C_k,h,w] (or None); mask: K bools (model available)."""
        H, W = imgs[0].shape[-2:]
        aligned = []
        for i, (f, ok) in enumerate(zip(feats, mask)):
            if ok and f is not None:
                a = self.align[i](f)
                if a.shape[-2:] != (H, W): a = F.interpolate(a, size=(H, W), mode="bilinear", align_corners=False)
            else:
                a = torch.zeros(imgs[0].shape[0], self.align[i].out_channels, H, W, device=imgs[0].device)
            aligned.append(a)
        fused = self.fuse(torch.cat(aligned, 1))
        logits = self.weight_head(fused)
        neg = torch.tensor([0.0 if ok else -1e4 for ok in mask], device=logits.device).view(1, -1, 1, 1)
        w = torch.softmax(logits + neg, dim=1)
        blend = sum(w[:, i:i + 1] * imgs[i] for i in range(self.k) if mask[i])
        return (blend + self.refine(fused)).clamp(0, 1), w

FUSION, FUSION_TRAINED = {}, {}
def init_fusion(task):
    # feature widths are discovered with a tiny dry run so the module matches the real taps
    x = torch.rand(1, 3, 64, 64, device=dev); chans = []
    for key, default in zip(ORDER, (64, 32, 48)):
        m = MODELS[task][key]
        if m:
            try: m(x); chans.append(m.feat_channels)
            except Exception as e: print("dry run failed for", task, key, e); chans.append(default)
        else: chans.append(default)
    net = FusionModule(tuple(chans)).to(dev).eval()
    path = FUSION_CKPT[task]
    if os.path.exists(path):
        ck = torch.load(path, map_location="cpu")
        net.load_state_dict(strip_module(ck.get("params", ck.get("model", ck))), strict=True)
        FUSION_TRAINED[task] = True
    else:
        FUSION_TRAINED[task] = False
    FUSION[task] = net
    print(f"fusion[{task}] feature widths {chans}  trained={FUSION_TRAINED[task]}")

for t in MODELS: init_fusion(t)

