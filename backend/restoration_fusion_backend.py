from PIL import Image
from skimage.metrics import peak_signal_noise_ratio, structural_similarity

def load_rgb(data: bytes, max_side=MAX_SIDE, size=None):
    im = Image.open(io.BytesIO(data)).convert("RGB")
    if size is not None:
        if im.size != size: im = im.resize(size, Image.LANCZOS)
    else:
        s = max(im.size)
        if s > max_side:
            r = max_side / s; im = im.resize((max(32, round(im.width * r)), max(32, round(im.height * r))), Image.LANCZOS)
    return im

def pad16(x):
    h, w = x.shape[-2:]; ph, pw = (-h) % 16, (-w) % 16
    if ph == 0 and pw == 0: return x, (h, w)
    mode = "reflect" if (ph < h and pw < w) else "replicate"
    return F.pad(x, (0, pw, 0, ph), mode=mode), (h, w)

def to_u8(t):  # [1,3,H,W] -> HxWx3 uint8
    return (t.clamp(0, 1)[0].permute(1, 2, 0).cpu().numpy() * 255.0).round().astype(np.uint8)

def to_y(u8):  # ITU-R BT.601 luma, as used by the Rain13k test configs (test_y_channel)
    f = u8.astype(np.float64) / 255.0
    return 65.481 * f[..., 0] + 128.553 * f[..., 1] + 24.966 * f[..., 2] + 16.0

def score(pred, gt, y_channel):
    if y_channel: pred, gt, ca = to_y(pred), to_y(gt), None
    else: pred, gt, ca = pred.astype(np.float64), gt.astype(np.float64), 2
    return float(peak_signal_noise_ratio(gt, pred, data_range=255)), float(structural_similarity(gt, pred, channel_axis=ca, data_range=255))

def data_url(u8):
    buf = io.BytesIO(); Image.fromarray(u8).save(buf, "PNG")
    return "data:image/png;base64," + base64.b64encode(buf.getvalue()).decode()

DISPLAY = {"hinet": "HINet", "sfnet": "SFNet", "adair": "AdaIR", "fusion": "Fusion (ours)"}

@torch.inference_mode()
def run_pipeline(image_bytes, task, gt_bytes=None):
    t_all = time.time()
    im = load_rgb(image_bytes)
    x0 = torch.from_numpy(np.asarray(im, dtype=np.float32) / 255.0).permute(2, 0, 1)[None].to(dev)
    x, (h, w) = pad16(x0)
    y_channel = task == "derain"
    gt_u8 = np.asarray(load_rgb(gt_bytes, size=im.size)) if gt_bytes else None

    outs, feats, items = {}, {}, []
    for key in ORDER:
        m = MODELS[task][key]; item = {"id": key, "name": DISPLAY[key], "available": False, "note": "", "image": None, "psnr": None, "ssim": None, "time_ms": None}
        if m is None:
            item["note"] = "Not loaded: " + LOAD_NOTES[task].get(key, "unknown")
        else:
            try:
                t = time.time(); torch.cuda.synchronize()
                out, feat = m(x); torch.cuda.synchronize()
                outs[key], feats[key] = out, feat
                item.update(available=True, time_ms=round((time.time() - t) * 1000))
            except torch.cuda.OutOfMemoryError:
                torch.cuda.empty_cache(); item["note"] = "Out of GPU memory. Try a smaller image."
            except Exception as e:
                item["note"] = f"{type(e).__name__}: {str(e)[:160]}"
        items.append(item)

    mask = [k in outs for k in ORDER]
    fusion_item = {"id": "fusion", "name": DISPLAY["fusion"], "available": False, "note": "", "image": None, "psnr": None, "ssim": None, "time_ms": None}
    if any(mask):
        try:
            t = time.time(); torch.cuda.synchronize()
            fused, _ = FUSION[task]([outs.get(k, x) for k in ORDER], [feats.get(k) for k in ORDER], mask)
            torch.cuda.synchronize()
            outs["fusion"] = fused
            fusion_item.update(available=True, time_ms=round((time.time() - t) * 1000))
            if not FUSION_TRAINED[task]:
                fusion_item["note"] = "Placeholder: fusion weights not trained yet, so this equals a plain average."
        except Exception as e:
            fusion_item["note"] = f"{type(e).__name__}: {str(e)[:160]}"
    else:
        fusion_item["note"] = "No base model produced an output."
    items.append(fusion_item)

    for it in items:
        if it["id"] in outs:
            u8 = to_u8(outs[it["id"]][..., :h, :w])
            it["image"] = data_url(u8)
            if gt_u8 is not None: it["psnr"], it["ssim"] = score(u8, gt_u8, y_channel)
    del outs, feats; torch.cuda.empty_cache()
    return {"task": task, "width": w, "height": h, "y_channel": y_channel, "has_gt": gt_u8 is not None,
            "fusion_trained": FUSION_TRAINED[task], "elapsed_ms": round((time.time() - t_all) * 1000),
            "input": data_url(np.asarray(im)), "results": items}

